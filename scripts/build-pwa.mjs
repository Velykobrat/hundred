import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { readAppShell } from './pwa-build-output.mjs';

const root = resolve(import.meta.dirname, '..');
const staticDir = join(root, '.next/static');
async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory()
    ? filesIn(join(directory, entry.name)) : join(directory, entry.name)))).flat();
}

// Cache every emitted runtime chunk, including lazy chunks, and self-hosted next/font files.
// Fail the build if Next's prerendered root output changes rather than ship an incomplete shell.
const shell = await readAppShell(root);
const manifest = await readFile(join(root, 'app/manifest.webmanifest'), 'utf8');
const template = await readFile(join(root, 'src/pwa/worker.js'), 'utf8');
const staticFiles = (await filesIn(staticDir)).filter(file => /\.(?:js|css|woff2?|ttf|otf)$/.test(file)).sort();
const assets = staticFiles.map(file => '/_next/static/' + relative(staticDir, file).replaceAll('\\', '/'));
assets.push('/pwa-192.png', '/pwa-512.png', '/brand/bebetter-text.svg');
for (const match of shell.matchAll(/(?:src|href)="(\/_next\/static\/[^"?]+)(?:\?[^"]*)?"/g)) {
  if (!assets.includes(match[1])) throw new Error(`Shell asset missing from precache: ${match[1]}`);
}
const hash = createHash('sha256').update(shell).update(manifest).update(template);
for (const asset of assets) {
  const file = asset.startsWith('/_next/static/')
    ? join(staticDir, asset.slice('/_next/static/'.length)) : join(root, 'public', asset);
  hash.update(asset).update(await readFile(file));
}
const config = { version: hash.digest('hex').slice(0, 20), shell, manifest, assets };
await writeFile(join(root, 'public/sw.js'), `// Generated by scripts/build-pwa.mjs. Do not edit.\nconst BUILD = ${JSON.stringify(config)};\n${template}`);
console.log(`PWA: generated worker ${config.version}, ${assets.length} local assets.`);
