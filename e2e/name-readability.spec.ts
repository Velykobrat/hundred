import { expect, test } from "./fixtures";
import { addPart } from "./helpers";

test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });

test("long names remain intact while cards and forms stay compact", async ({ page }) => {
  await page.goto("/");
  await page.locator(".home-header-create").click();
  const input = page.getByLabel("Назва", { exact: true });
  const hint = page.getByText("Коротша назва краще читається на картці.");
  await input.fill("A".repeat(40));
  await expect(hint).toHaveCount(0);
  await input.fill("A".repeat(41));
  await expect(hint).toBeVisible();
  const whole = "W".repeat(120);
  await input.fill(whole);
  await expect(page.getByText("120 / 120")).toBeVisible();
  await input.pressSequentially("X");
  await expect(input).toHaveValue(whole);
  await page.getByRole("button", { name: "Створити ціле", exact: true }).click();
  const part = "P".repeat(120);
  await page.locator(".add-part-button").click();
  const dialog = page.getByRole("dialog", { name: "Додати частину" });
  const partInput = dialog.getByLabel("Назва частини");
  await partInput.fill("P".repeat(80));
  await expect(dialog.getByText("Коротша назва краще читається на картці.")).toHaveCount(0);
  await partInput.fill(part);
  await expect(dialog.getByText("Коротша назва краще читається на картці.")).toBeVisible();
  await dialog.getByRole("button", { name: "Додати частину", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await addPart(page, "Short part");
  const cards = page.locator(".structural-card");
  await expect(cards.first().locator("strong")).toHaveCSS("-webkit-line-clamp", "3");
  expect((await cards.first().boundingBox())!.height).toBe((await cards.last().boundingBox())!.height);
  await page.getByRole("button", { name: `Дії для «${part}»` }).click();
  await expect(page.getByRole("dialog", { name: part }).getByRole("heading", { name: part })).toBeVisible();
  await page.getByRole("button", { name: "Редагувати частину" }).click();
  await expect(page.getByRole("dialog", { name: "Редагувати частину" }).getByText("Коротша назва краще читається на картці.")).toBeVisible();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Головна", exact: true }).click();
  const wholeCard = page.locator(".resource-card").first();
  await expect(wholeCard.locator(".resource-card-name")).toHaveCSS("-webkit-line-clamp", "2");
  await expect(wholeCard.getByRole("button", { name: `Відкрити ціле «${whole}»` })).toBeVisible();
  await page.getByRole("button", { name: `Дії для «${whole}»` }).click();
  await expect(page.getByRole("dialog", { name: whole }).getByRole("heading", { name: whole })).toBeVisible();
  await page.getByRole("button", { name: "Редагувати ціле" }).click();
  await expect(page.getByRole("dialog", { name: "Редагувати ціле" }).getByText("Коротша назва краще читається на картці.")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
